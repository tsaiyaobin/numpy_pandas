import pandas as pd

scores = {'國' : {'王一':65, '李二':90, '張三':81, '黃四':79},
          '英' : {'王一':92, '李二':82, '張三':75, '黃四':56},
          '數' : {'王一':81, '李二':82, '張三':73, '黃四':52},
          '自' : {'王一':92, '李二':28, '張三':52, '黃四':15},
          '社' : {'王一':64, '李二':86, '張三':94, '黃四':86}}

# 鍵會自動成為欄位名
df1 = pd.DataFrame(scores)
#       國  英  數  自  社
# 王一  65  92  81  92  64
# 李二  90  82  82  28  86
# 張三  81  75  73  52  94
# 黃四  79  56  52  15  86

#------------以欄位名稱取值-------------
# df['欄位名稱']
print(df1['自'])

# 王一    92
# 李二    28
# 張三    52
# 黃四    15
# Name: 自, dtype: int64

#------------取得兩個欄位以上的資料------------
# df[[欄位名稱1,欄位名稱2,.....]] ，須將欄位名稱化為串列
print(df1[['國', '英', '數']])

#      國   英   數
# 王一  65  92  81
# 李二  90  82  82
# 張三  81  75  73
# 黃四  79  56  52

#------------利用邏輯運算來取值------------
#例如國文 >=80 的所有學生資料
print(df1[ df1['國'] >= 80 ])

#      國   英   數   自   社
# 李二  90  82  82  28  86
# 張三  81  75  73  52  94
