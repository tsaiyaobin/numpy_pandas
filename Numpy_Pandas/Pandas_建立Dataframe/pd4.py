import pandas as pd
#----------利用字典建立 DataFrame ------------
scores = {'國' : {'王一':65, '李二':90, '張三':81, '黃四':79},
          '英' : {'王一':92, '李二':82, '張三':75, '黃四':56},
          '數' : {'王一':81, '李二':82, '張三':73, '黃四':52},
          '自' : {'王一':92, '李二':28, '張三':52, '黃四':15},
          '社' : {'王一':64, '李二':86, '張三':94, '黃四':86}}

# 鍵會自動成為欄位名
df1 = pd.DataFrame(scores)
print(df1)

#      國   英   數   自   社
# 王一  65  92  81  92  64
# 李二  90  82  82  28  86
# 張三  81  75  73  52  94
# 黃四  79  56  52  15  86

#----------利用 Series 建立 DataFrame------------
se1 = pd.Series({'王一':65, '李二':90, '張三':81, '黃四':79})
se2 = pd.Series({'王一':92, '李二':82, '張三':75, '黃四':56})
se3 = pd.Series({'王一':81, '李二':82, '張三':73, '黃四':52})
se4 = pd.Series({'王一':92, '李二':28, '張三':52, '黃四':15})
se5 = pd.Series({'王一':64, '李二':86, '張三':94, '黃四':86})

df2 = pd.DataFrame({'國':se1,'英':se2,'數':se3,'自':se4,'社':se5})
print(df2)
#      國   英   數   自   社
# 王一  65  92  81  92  64
# 李二  90  82  82  28  86
# 張三  81  75  73  52  94
# 黃四  79  56  52  15  86

#----------利用 concat 函數合併 Series 物件------------
se1 = pd.Series({'王一':65, '李二':90, '張三':81, '黃四':79})
se2 = pd.Series({'王一':92, '李二':82, '張三':75, '黃四':56})
se3 = pd.Series({'王一':81, '李二':82, '張三':73, '黃四':52})
se4 = pd.Series({'王一':92, '李二':28, '張三':52, '黃四':15})
se5 = pd.Series({'王一':64, '李二':86, '張三':94, '黃四':86})
df3 = pd.concat([se1,se2,se3,se4,se5],axis=1)
df3.columns=['國','英','數','自','社']
print(df3)



