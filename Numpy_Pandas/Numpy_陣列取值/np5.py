import numpy as np

#-----------一維陣列取值------------
# 一維陣列變數[索引]
# 一維陣列變數[起始索引 : 終止索引 [:間隔索引]] => 取得一個範圍的值
na = np.arange(0,6)
print(na) # [0 1 2 3 4 5]

print(na[1]) # 1

print(na[0:5]) # [0 1 2 3 4]

print(na[1:4:2]) # [1 3]

print(na[:]) # [0 1 2 3 4 5]

print(na[3:]) # [3 4 5]

print(na[:3]) # [0 1 2]

# 倒過來輸出
print(na[5:1:-1]) # [5 4 3 2]