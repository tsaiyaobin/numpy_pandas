import pandas as pd

scores = {'國' : {'王一':65, '李二':90, '張三':81, '黃四':79},
          '英' : {'王一':92, '李二':82, '張三':75, '黃四':56},
          '數' : {'王一':81, '李二':82, '張三':73, '黃四':52},
          '自' : {'王一':92, '李二':28, '張三':52, '黃四':15},
          '社' : {'王一':64, '李二':86, '張三':94, '黃四':86}}

# 鍵會自動成為欄位名
df1 = pd.DataFrame(scores)
#       國  英  數  自  社
# 王一  65  92  81  92  64
# 李二  90  82  82  28  86
# 張三  81  75  73  52  94
# 黃四  79  56  52  15  86

#--------------以索引及欄位編號取得資料 : iloc -------------------
# 語法 df.iloc[ 索引編號 , 欄位標號 ] 
# 例如取得 王一的自然成績
print(df1.iloc[0,3]) # 92

# 例如取得 張三的國文及自然成績
print(df1.iloc[2, [0, 3]])

# 國    81
# 自    52
# Name: 張三, dtype: int64

# 例如取得 王一、張三 的 數學跟社會 成績
print(df1.iloc[[0, 2], [2, 4]])

#      數   社
# 王一  81  64
# 張三  73  94

# 例如取得 王一到張三 的 英文到自然 的成績
print(df1.iloc[0:3, 1:4])

#      英   數   自
# 王一  92  81  92
# 李二  82  82  28
# 張三  75  73  52

# 例如取得李二的所有成績
print(df1.iloc[1, :])
# 國    90
# 英    82
# 數    82
# 自    28
# 社    86
# Name: 李二, dtype: int64

# 例如取得 從頭到張三 的 英文到自然 的成績
print(df1.iloc[:3, 1:4])
#      英   數   自
# 王一  92  81  92
# 李二  82  82  28
# 張三  75  73  52

# 例如取得 從李二到最後 的 數學到社會 的成績
print(df1.iloc[1:, 2:5])

#      數   自   社
# 李二  82  28  86
# 張三  73  52  94
# 黃四  52  15  86


































