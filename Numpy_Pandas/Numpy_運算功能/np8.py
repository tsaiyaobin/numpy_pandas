import numpy as np

a = np.arange(1, 10).reshape(3, 3)
b = np.arange(10, 19).reshape(3, 3)
print('a:', a)
#a: [[1 2 3]
#    [4 5 6]
#    [7 8 9]]

print('b:', b)
#b: [[10 11 12]
#    [13 14 15]
#    [16 17 18]]

#--------------對單一陣列進行運算-------------
print('a 陣列元素都加值: \n', a + 1)

# a 陣列元素都加值: 
# [[ 2  3  4]
#  [ 5  6  7]
#  [ 8  9 10]]

print('a 陣列元素都平方: \n', a ** 2)

# a 陣列元素都平方: 
# [[ 1  4  9]
#  [16 25 36]
#  [49 64 81]]

print('a 陣列元素加上判斷: \n', a < 5)

# a 陣列元素加上判斷: 
# [[ True  True  True]
#  [ True False False]
#  [False False False]]

#--------------取出指定的陣列的值進行運算-------------
print('a 陣列取出第一個 row 都加 1 :',a[0, :] + 1)
# a 陣列取出第一個 row 都加 1 : [2 3 4]
print('a 陣列取出第一個 col 都加 1 :',a[:, 0] + 1)
# a 陣列取出第一個 col 都加 1 : [2 5 8]

#-----------------對多個陣列進行運算----------------
print('a b 對應陣列進行相加:',a + b)
# a b 對應陣列進行相加:
# [[11 13 15]
#  [17 19 21]
#  [23 25 27]]

print('a b 對應陣列進行相乘:',a * b)
# a b 對應陣列進行相乘: 
# [[ 10  22  36]
#  [ 52  70  90]
#  [112 136 162]]

''' 內積 '''
print('a b 對應陣列進行內積:',np.dot(a, b))
# a b 對應陣列進行內積: 
# [[ 84  90  96]
#  [201 216 231]
#  [318 342 366]]

 
