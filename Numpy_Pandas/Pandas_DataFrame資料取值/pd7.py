import pandas as pd

scores = {'國' : {'王一':65, '李二':90, '張三':81, '黃四':79},
          '英' : {'王一':92, '李二':82, '張三':75, '黃四':56},
          '數' : {'王一':81, '李二':82, '張三':73, '黃四':52},
          '自' : {'王一':92, '李二':28, '張三':52, '黃四':15},
          '社' : {'王一':64, '李二':86, '張三':94, '黃四':86}}

# 鍵會自動成為欄位名
df1 = pd.DataFrame(scores)
#       國  英  數  自  社
# 王一  65  92  81  92  64
# 李二  90  82  82  28  86
# 張三  81  75  73  52  94
# 黃四  79  56  52  15  86

#--------------以索引及欄位名稱取得資料 : loc -------------------

# 例如取得張三的數學成績
print(df1.loc['張三', '數']) # 73

# 若要取得多個索引名稱或欄位名稱就必須組合成串列
# 例如取得 黃四 的 國文跟英文 成績
print(df1.loc["黃四", ['國', '英'] ])

# 國    79
# 英    56
# Name: 黃四, dtype: int64

# 例如取得 王一、張三 的 數學跟社會 成績
print(df1.loc[ ["王一", "張三"], ['數', '社'] ])

#      數   社
# 王一  81  64
# 張三  73  94

# 例如取得 王一到張三 的 英文到自然 的成績
print(df1.loc[ "王一":"張三" , '英':'自' ])

#      英   數   自
# 王一  92  81  92
# 李二  82  82  28
# 張三  75  73  52

# 例如取得李二的所有成績
print(df1.loc[ "李二" , : ])

# 國    90
# 英    82
# 數    82
# 自    28
# 社    86
# Name: 李二, dtype: int64

# 例如取得 從頭到張三 的 英文到自然 的成績
print(df1.loc[ : '張三' , '英':'自'])

#      英   數   自
# 王一  92  81  92
# 李二  82  82  28
# 張三  75  73  52

# 例如取得 從李二到最後 的 數學到社會 的成績
print(df1.loc['李二' : , '數' : '社'])

#      數   自   社
# 李二  82  28  86
# 張三  73  52  94
# 黃四  52  15  86
































