import pandas as pd

scores = {'國' : {'王一':65, '李二':90, '張三':81, '黃四':79},
          '英' : {'王一':92, '李二':82, '張三':75, '黃四':56},
          '數' : {'王一':81, '李二':82, '張三':73, '黃四':52},
          '自' : {'王一':92, '李二':28, '張三':52, '黃四':15},
          '社' : {'王一':64, '李二':86, '張三':94, '黃四':86}}

# 鍵會自動成為欄位名
df1 = pd.DataFrame(scores)
#       國  英  數  自  社
# 王一  65  92  81  92  64
# 李二  90  82  82  28  86
# 張三  81  75  73  52  94
# 黃四  79  56  52  15  86

#------------ 依值排序:sort_values() ------------
# 語法df.sort_values( by = 欄位 [, ascending = 布林值])
# by 作為排序值的欄位名稱, ascending = False 為遞減排序
print(df1.sort_values( by = "數", ascending = False))

#      國   英   數   自   社
# 李二  90  82  82  28  86
# 王一  65  92  81  92  64
# 張三  81  75  73  52  94
# 黃四  79  56  52  15  86

#------------ 依索引排序:sort_index() ------------
# 語法df.sort_index( axis = 軸向編號 [, ascending = 布林值])
# axis = 0 代表橫列，1 代表直行
print(df1.sort_index( axis = 0))

#       國   英   數   自   社
# 張三  81  75  73  52  94
# 李二  90  82  82  28  86
# 王一  65  92  81  92  64
# 黃四  79  56  52  15  86

#------------ 資料修改 ------------
df1.loc['王一']['數'] = 90
df1.loc['黃四', : ] = 100
print(df1)

#       國    英    數    自    社
# 王一   65   92   90   92   64
