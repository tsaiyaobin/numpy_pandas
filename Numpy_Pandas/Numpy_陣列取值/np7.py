import numpy as np

'''
---------------------------------------------------------------------------------------------------
rand(d0, d1...dn)	         | 依設定維度產生陣列，返回 0~1 之間的隨機浮點數
---------------------------------------------------------------------------------------------------
randn(d0, d1...dn)	         | 依設定維度產生陣列，返回標準常態分佈（均值為 0，標準差為 1）的隨機浮點數
---------------------------------------------------------------------------------------------------
randint(最低 [, 最高, size])	 | 依設定範圍(包含最低不含最高)返回隨機整數資料，size可設定返回資料的維度。
---------------------------------------------------------------------------------------------------
random(size)	
random_sample(size)          |在指定形狀的陣列 size 內產生隨機浮點數，範圍 0~1 之間
sample(size)
---------------------------------------------------------------------------------------------------
choice(a[, size, replace])	 |在指定的陣列 a 或範圍內隨機選擇指定形狀 size 的數據，若 replace=False 則不重複選取
---------------------------------------------------------------------------------------------------
'''
print('1. 產生 2x3 之上的隨機浮點數\n', np.random.rand(2, 3))
# [[0.41923947 0.38745207 0.83175317][0.56830683 0.37562228 0.17970301]]

print('2. 產生 0~4 之間的隨機整數\n', np.random.randint(5)) # 2

print('3. 產生 2~4 (不含 5) 之間的隨機整數\n', np.random.randint(2, 5, size=(5,)))
# [4 2 3 2 4]

print('4. 產生 3 個 0~1 之間的隨機數\n', np.random.random_sample(3))
# [0.58801478 0.43226219 0.46865536]

print('5. 從數組 [5, 2, 3] 中隨機選擇\n', np.random.choice([5, 2, 3])) # 5

print('6. 產生 0~4 (不含 5) 之間的隨機整數\n', np.random.choice(5)) # 1

print('7. 在 0~42 (不含 43) 之間不重複選擇 6 個隨機數\n', np.random.choice(43, 6, replace=False))
#  [ 9 23  6 42 22 25]