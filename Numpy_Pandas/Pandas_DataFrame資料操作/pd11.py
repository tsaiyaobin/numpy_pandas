import pandas as pd

scores = {'國' : {'王一':65, '李二':90, '張三':81, '黃四':79},
          '英' : {'王一':92, '李二':82, '張三':75, '黃四':56},
          '數' : {'王一':81, '李二':82, '張三':73, '黃四':52},
          '自' : {'王一':92, '李二':28, '張三':52, '黃四':15},
          '社' : {'王一':64, '李二':86, '張三':94, '黃四':86}}

# 鍵會自動成為欄位名
df1 = pd.DataFrame(scores)
#       國  英  數  自  社
# 王一  65  92  81  92  64
# 李二  90  82  82  28  86
# 張三  81  75  73  52  94
# 黃四  79  56  52  15  86

#--------------- 刪除 DataFrame 資料----------------
# 資料變數 = df.drop(索引或欄位名稱[, axis = 軸向編號])
# 例如刪除王一資料
new_df = df1.drop("王一")
print(new_df)

#      國   英   數   自   社
# 李二  90  82  82  28  86
# 張三  81  75  73  52  94
# 黃四  79  56  52  15  86

# 例如刪除數學成績
dl_math = df1.drop("數", axis = 1)
print(dl_math)

#      國   英   自   社
# 王一  65  92  92  64
# 李二  90  82  28  86
# 張三  81  75  52  94
# 黃四  79  56  15  86

# 例如刪除國文英文成績
dl_ch_eg = df1.drop(["國", "英"], axis = 1)
print(dl_ch_eg)

#      數   自   社
# 王一  81  92  64
# 李二  82  28  86
# 張三  73  52  94
# 黃四  52  15  86


#--------------- 刪除連續列欄範圍的資料----------------
# 刪除連續橫列
# df.drop(df.index[ 起始編號 : 終止編號 ] [, axis = 軸向編號])
print(df1.drop(df1.index[1:4]))

#      國   英   數   自   社
# 王一  65  92  81  92  64

# 刪除連續直欄
# df.drop(df.columns[ 起始編號 : 終止編號 ] [, axis = 軸向編號])
print(df1.drop(df1.columns[1:4], axis = 1))

#      國   社
# 王一  65  64
# 李二  90  86
# 張三  81  94
# 黃四  79  86















